import 'package:dartz/dartz.dart';
import 'package:tfg1/domain/entities/enum/match_event_enum.dart';
import 'package:tfg1/domain/entities/match.dart';
import 'package:tfg1/core/errors/failure/failure.dart';
import 'package:tfg1/domain/entities/enum/match_status.dart';
import 'package:tfg1/domain/entities/match_event.dart';
import 'package:tfg1/domain/entities/player_stats.dart';
import 'package:tfg1/domain/i_repositories/i_match_event_repository.dart';
import 'package:tfg1/domain/i_repositories/i_match_repository.dart';
import 'package:tfg1/domain/i_repositories/i_player_repository.dart';

class FinishMatch {
  final IMatchRepository _matchRepository;
  final IMatchEventRepository _matchEventRepository;
  final IPlayerRepository _playerRepository;

  FinishMatch(this._matchRepository, this._matchEventRepository, this._playerRepository);

  Future<Either<Failure, void>> call(Match match) async {
    Either<Failure, List<MatchEvent>> events = await _matchEventRepository.getMatchEventsByMatch(match.id);
    if (events.isLeft()) { // If it is an error, return the error
      return events;
    }

    // If it is successful, calculate the goals scored and conceded based on the match events
    final List<MatchEvent> matchEvents = events.getOrElse(() => []);

    int goalsScored = 0;
    int goalsConceded = 0;

    for (int i = 0; i < matchEvents.length; i++) {
      if (matchEvents[i].type == MatchEventEnum.scoreGoal) {
        goalsScored++;
      } else if (matchEvents[i].type == MatchEventEnum.concedeGoal || matchEvents[i].type == MatchEventEnum.ownGoal) {
        goalsConceded++;
      }
    }

    Match updatedMatch = Match(
      id: match.id,
      teamId: match.teamId,
      opponent: match.opponent,
      goalsScored: goalsScored,
      goalsConceded: goalsConceded,
      date: match.date,
      status: MatchStatus.finished, // Set status to finished to indicate the match is finished
      lineups: match.lineups,
    );
    Either<Failure, void> result = await _matchRepository.updateMatch(updatedMatch);
    if (result.isLeft()) { // If it is an error, return the error
      return result;
    }
    List<int> playerIds = matchEvents.map((event) => event.playerId).whereType<int>().toSet().toList();
    int i = 0;
    while (i < playerIds.length) {
      PlayerStats playerStats = _getPlayerStats(matchEvents, playerIds[i]);
      result = await _playerRepository.updatePlayerStats(playerStats);
      if (result.isLeft()) { // If it is an error, return the error
        return result;
      }
      i++;
    }
    return result;
  }

  PlayerStats _getPlayerStats(List<MatchEvent> events, int playerId) {
    
    int idPlayer = playerId;
    int goals = 0;
    int assists = 0;
    int yellowCards = 0;
    int redCards = 0;

    for (int i = 0; i < events.length; i++) {
      if (events[i].playerId == idPlayer) {
        if (events[i].type == MatchEventEnum.scoreGoal) {
          goals++;
        } else if (events[i].type == MatchEventEnum.yellowCard) {
          yellowCards++;
        } else if (events[i].type == MatchEventEnum.redCard) {
          redCards++;
        } else if (events[i].type == MatchEventEnum.assist) {
          assists++;
        }
      }
    }

    return PlayerStats(
      id: 0, // This should be generated by the database when saving the stats
      playerId: idPlayer,
      goals: goals,
      assists: assists,
      yellowCards: yellowCards,
      redCards: redCards,
    );
  }

}